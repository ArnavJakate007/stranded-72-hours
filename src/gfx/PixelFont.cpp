PixelFont::~PixelFont() {
    if (atlas_.id) UnloadTexture(atlas_);
}

void PixelFont::load() {
    int total = 0;
    for (const auto& g : table()) total += static_cast<int>(g.rows[0].size()) + 1;
    Image img = GenImageColor(total, 9, BLANK);
    int x = 0;
    for (const auto& g : table()) {
        int w = static_cast<int>(g.rows[0].size());
        for (size_t r = 0; r < g.rows.size(); ++r)
            for (int k = 0; k < w; ++k)
                if (g.rows[r][k] == '#') ImageDrawPixel(&img, x + k, static_cast<int>(r), WHITE);
        int bytes = 0;
        int cp = GetCodepointNext(g.ch, &bytes);
        glyphs_[cp] = Glyph{Rectangle{static_cast<float>(x), 0, static_cast<float>(w), 9}, w};
        x += w + 1;
    }
    atlas_ = LoadTextureFromImage(img);
    UnloadImage(img);
}

const PixelFont::Glyph* PixelFont::glyph(int cp) const {
    auto it = glyphs_.find(cp);
    if (it != glyphs_.end()) return &it->second;
    it = glyphs_.find('?');
    return it == glyphs_.end() ? nullptr : &it->second;
}

int PixelFont::width(const std::string& text, int scale) const {
    int w = 0;
    const char* p = text.c_str();
    while (*p) {
        int bytes = 0;
        int cp = GetCodepointNext(p, &bytes);
        p += bytes;
        if (cp == ' ') {
            w += 4;
            continue;
        }
        const Glyph* g = glyph(cp);
        w += (g ? g->w : 3) + 1;
    }
    return (w > 0 ? w - 1 : 0) * scale;
}

void PixelFont::drawRaw(const std::string& text, float x, float y, Color color, int scale) const {
    float cx = std::round(x), cy = std::round(y);
    const char* p = text.c_str();
    while (*p) {
        int bytes = 0;
        int cp = GetCodepointNext(p, &bytes);
        p += bytes;
        if (cp == ' ') {
            cx += 4 * scale;
            continue;
        }
        const Glyph* g = glyph(cp);
        if (!g) continue;
        DrawTexturePro(atlas_, g->src, Rectangle{cx, cy, g->src.width * scale, g->src.height * scale}, Vector2{0, 0}, 0, color);
        cx += (g->w + 1) * scale;
    }
}

void PixelFont::draw(const std::string& text, float x, float y, Color color, int scale, bool shadow) const {
    if (shadow) drawRaw(text, x, y + scale, Color{3, 5, 10, color.a}, scale);
    drawRaw(text, x, y, color, scale);
}
